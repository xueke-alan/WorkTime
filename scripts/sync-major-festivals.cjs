"use strict";
// Generate offline festival dates from the bundled lunar library, independent of holiday notices.
const fs = require("node:fs");
const path = require("node:path");
const { Lunar, Solar } = require("../assets/vendor/lunar.js");
function build() {
  const years = {};
  for (let year = 1900; year <= 2100; year++) {
    years[year] = [
      Lunar.fromYmd(year, 1, 1).getSolar(),
      Solar.fromYmd(year, 4, 5).getLunar().getJieQiTable()["清明"],
      Lunar.fromYmd(year, 5, 5).getSolar(),
      Lunar.fromYmd(year, 8, 15).getSolar(),
    ].map((date) => date.toYmd().slice(5));
  }
  const data = {
    fixed: { "01-01": "元旦", "05-01": "劳动节", "10-01": "国庆" },
    movableNames: ["春节", "清明", "端午", "中秋"],
    years,
  };
  return (
    '"use strict";\n/** Generated by scripts/sync-major-festivals.cjs; festival dates are not days off. */\nWorkTimeApp.data.majorFestivals = ' +
    JSON.stringify(data, null, 2) +
    ";\n"
  );
}
if (require.main === module) {
  const target = path.resolve(__dirname, "../assets/data/major-festivals.js");
  const content = build();
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== content)
      throw Error("Major festival data is out of date");
  } else fs.writeFileSync(target, content);
}
module.exports = { build };
