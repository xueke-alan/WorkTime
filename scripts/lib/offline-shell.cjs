"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
/** Describe the actual entry bytes, for both file-compatible source and published bundles. */
function offlineShell(root, { published = false, version } = {}) {
  const hash = (value) =>
    crypto.createHash("sha256").update(value).digest("hex").slice(0, 16);
  const read = (asset) => {
    const file = path.resolve(root, asset);
    if (!file.startsWith(path.resolve(root) + path.sep))
      throw Error("Offline asset escapes site");
    return fs.readFileSync(file);
  };
  const html = read("index.html").toString();
  const entries = new Set(["index.html", "manifest.webmanifest"]);
  for (const match of html.matchAll(/\b(?:src|href)="((?:assets\/)[^"#]+)"/g))
    entries.add(match[1]);
  const dynamic = [
    ...["core", "date", "view", "startup"].map(
      (name) => `assets/js/ui/${name}-runtime.min.js`,
    ),
    ...["zh-CN", "zh-TW", "zh-HK", "en", "ja", "ko"].map(
      (id) => `assets/js/locales/runtime/${id}.js`,
    ),
    "assets/vendor/lunar.min.js",
    "assets/css/analysis.css",
    "assets/css/game-session.css",
  ];
  for (const asset of dynamic)
    entries.add(asset + (published ? "?v=" + hash(read(asset)) : ""));
  // Include fonts and artwork used by the critical stylesheet, retaining its URL resolution.
  for (const asset of [...entries]) {
    const clean = asset.split("?")[0];
    if (!clean.endsWith(".css")) continue;
    for (const match of read(clean)
      .toString()
      .matchAll(/url\(\s*["']?([^\s)"']+)/g)) {
      if (/^(?:data:|https?:|\/|#)/.test(match[1])) continue;
      entries.add(
        path.posix.normalize(
          path.posix.join(path.posix.dirname(clean), match[1]),
        ),
      );
    }
  }
  const assets = [...entries].sort();
  // Source checkouts may contain CRLF while git archives use LF. Equivalent
  // text must produce the same checked-in manifest. Published URL hashes still
  // describe the exact bytes produced by bundle-site.cjs.
  const contentHash = (asset) => {
    const clean = asset.split("?")[0];
    const bytes = read(clean);
    return hash(
      !published && /\.(?:js|css|html|json|webmanifest|svg)$/.test(clean)
        ? bytes.toString().replace(/\r\n?/g, "\n")
        : bytes,
    );
  };
  const digest = hash(
    assets.map((asset) => asset + ":" + contentHash(asset)).join("\n"),
  );
  version ||= JSON.parse(read("package.json").toString()).version;
  return (
    "// Generated by scripts/lib/offline-shell.cjs; do not edit.\nself.WORKTIME_SHELL = " +
    JSON.stringify({ cache: `worktime-shell-${version}-${digest}`, assets }) +
    ";\n"
  );
}
module.exports = { offlineShell };
