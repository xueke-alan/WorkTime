"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const cities = JSON.parse(
  fs.readFileSync(
    path.join(root, "assets/data/weather-locations.json"),
    "utf8",
  ),
);
if (
  !cities.length ||
  new Set(cities.map((city) => city.id)).size !== cities.length ||
  new Set(cities.map((city) => city.weatherKey)).size !== cities.length ||
  cities.some(
    (city) =>
      !/^\d{6}$/.test(city.districtId) || !city.name || !city.weatherKey,
  )
)
  throw Error("办公城市配置无效或重复");
const directory = {
  version: "baidu-offices-v1",
  source:
    "https://mapopen-website-wiki.bj.bcebos.com/cityList/weather_district_id.csv",
  cities: cities.map((city) => ({ ...city, label: city.name })),
};
fs.writeFileSync(
  path.join(root, "assets/data/weather-cities.js"),
  "// Generated by scripts/sync-weather-cities.cjs; Baidu office districts.\n" +
    "(function(g){g.WorkWeatherCities=" +
    JSON.stringify(directory) +
    ';})(typeof window==="undefined"?globalThis:window);\n',
);
console.log("Office cities:", cities.length);
