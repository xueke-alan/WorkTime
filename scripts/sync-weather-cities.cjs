"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const cities = JSON.parse(
  fs.readFileSync(
    path.join(root, "assets/data/weather-locations.json"),
    "utf8",
  ),
);
if (
  !cities.length ||
  new Set(cities.map((city) => city.id)).size !== cities.length ||
  new Set(cities.map((city) => city.weatherKey)).size !== cities.length ||
  cities.some(
    (city) =>
      !/^\d{6}$/.test(city.districtId) || !city.name || !city.weatherKey,
  )
)
  throw Error("办公城市配置无效或重复");
const directory = {
  version: "baidu-offices-v1",
  source:
    "https://mapopen-website-wiki.bj.bcebos.com/cityList/weather_district_id.csv",
  cities: cities.map((city) => ({ ...city, label: city.name })),
};
const destination = path.join(root, "assets/data/weather-cities.js");
const generated =
  "// Generated by scripts/sync-weather-cities.cjs; Baidu office districts.\n" +
  "WorkTimeApp.data.weatherCities=" +
  JSON.stringify(directory) +
  ";\n";
if (process.argv.includes("--check")) {
  if (
    fs.readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== generated
  )
    throw Error(
      "城市生成文件与weather-locations.json不一致，请运行城市同步脚本",
    );
  console.log("Office city generated data verified:", cities.length);
} else {
  const temporary = destination + ".tmp";
  try {
    fs.writeFileSync(temporary, generated);
    fs.renameSync(temporary, destination);
  } finally {
    if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
  }
  console.log("Office cities:", cities.length);
}
