"use strict";
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const source =
  "https://raw.githubusercontent.com/qwd/LocationList/master/China-City-List-latest.csv";
async function main() {
  const response = await fetch(source);
  if (!response.ok) throw Error("城市目录下载失败: " + response.status);
  const lines = (await response.text())
    .trim()
    .split(/\r?\n/)
    .map((s) => s.trim());
  const columns = lines[1].split(",");
  const allCities = lines
    .slice(2)
    .filter(Boolean)
    .map((line) => {
      const values = line
        .match(/("(?:[^"]|"")*"|[^,]*)(,|$)/g)
        .filter((v) => v !== "")
        .map((v) =>
          v.replace(/,$/, "").replace(/^"|"$/g, "").replace(/""/g, '"'),
        );
      const row = Object.fromEntries(values.map((v, i) => [columns[i], v]));
      const city = {
        id: row.Location_ID,
        name: row.Location_Name_ZH,
        province: row.Adm1_Name_ZH,
        prefecture: row.Adm2_Name_ZH,
        latitude: Number(row.Latitude),
        longitude: Number(row.Longitude),
      };
      city.provinceId = crypto
        .createHash("sha256")
        .update(city.province)
        .digest("hex")
        .slice(0, 8);
      city.label = [
        ...new Set([city.province, city.prefecture, city.name]),
      ].join(" / ");
      if (
        !/^[A-Za-z0-9]+$/.test(city.id) ||
        !city.name ||
        !city.province ||
        !Number.isFinite(city.latitude) ||
        !Number.isFinite(city.longitude) ||
        Math.abs(city.latitude) > 90 ||
        Math.abs(city.longitude) > 180
      )
        throw Error("城市目录存在无效坐标或标识");
      return city;
    });
  if (
    allCities.length < 300 ||
    new Set(allCities.map((c) => c.id)).size !== allCities.length
  )
    throw Error("城市目录不完整或标识重复");
  const selected = JSON.parse(
    fs.readFileSync(
      path.resolve(__dirname, "../assets/data/weather-locations.json"),
      "utf8",
    ),
  );
  if (!selected.length || new Set(selected).size !== selected.length)
    throw Error("可选城市标识为空或重复");
  const cities = selected.map((id) => {
    const city = allCities.find((c) => c.id === id);
    if (!city) throw Error("城市目录未找到标识: " + id);
    return city;
  });
  const directory = { version: lines[0].split(",")[0], source, cities };
  fs.writeFileSync(
    path.resolve(__dirname, "../assets/data/weather-cities.js"),
    "// Generated by scripts/sync-weather-cities.cjs; QWeather LocationList.\n" +
      "(function(g){g.WorkWeatherCities=" +
      JSON.stringify(directory) +
      ';})(typeof window==="undefined"?globalThis:window);\n',
  );
  console.log(
    "Cities:",
    cities.length,
    "Provinces:",
    new Set(cities.map((c) => c.provinceId)).size,
  );
}
if (require.main === module)
  main().catch((e) => {
    console.error(e.message);
    process.exitCode = 1;
  });
