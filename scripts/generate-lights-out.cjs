"use strict";
/** Original, reproducible levels. Run explicitly; never generate at startup. */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = vm.createContext({ WorkTimeApp: { games: {} } });
vm.runInContext(
  fs.readFileSync(
    path.join(root, "assets/js/games/lights-out-rules.js"),
    "utf8",
  ),
  context,
);
const rules = context.WorkTimeApp.games.lightsOutRules;
let seed = 20261111;
function random() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
}
const levels = [];
for (const size of rules.sizes) {
  const candidates = new Map();
  // Enumerate every 4x4 board; larger sizes sample balanced press patterns.
  const count = size === 4 ? 65536 : 12000;
  for (let sample = 0; sample < count; sample++) {
    const board = Array(size * size).fill(0);
    for (let i = 0; i < board.length; i++) {
      const selected = size === 4 ? (sample >>> i) & 1 : random() < 0.5;
      if (selected) rules.flip(board, i, size);
    }
    const text = board.join("");
    if (rules.won(board) || candidates.has(text)) continue;
    const solution = Array.from(rules.solve(board, size));
    candidates.set(text, {
      size,
      board: text,
      minimum: solution.length,
      solution,
    });
  }
  const sorted = [...candidates.values()].sort(
    (a, b) => a.minimum - b.minimum || a.board.localeCompare(b.board),
  );
  const hard = sorted.slice(-rules.perChapter);
  const threshold = { 4: 7, 5: 13, 6: 24, 7: 32 }[size];
  if (
    hard.length !== rules.perChapter ||
    hard.some((l) => l.minimum < threshold)
  )
    throw Error("Insufficient hard puzzles: " + size);
  for (let i = 0; i < rules.perChapter; i++) {
    const level = hard[i];
    levels.push({
      id: `lights-hard-${size}-${String(i + 1).padStart(2, "0")}`,
      ...level,
    });
  }
}
const output =
  '"use strict";\n// Original fixed puzzles; generated by scripts/generate-lights-out.cjs.\nWorkTimeApp.data.lightsOut = ' +
  JSON.stringify(levels) +
  ";\n";
const target = path.join(root, "assets/data/lights-out.js");
if (process.argv.includes("--check")) {
  require("node:assert/strict").equal(fs.readFileSync(target, "utf8"), output);
} else fs.writeFileSync(target, output);
console.log(
  "100 hard Lights Out levels: four sizes, no introductory puzzles, exact minima verified.",
);
for (const size of rules.sizes) {
  const group = levels.filter((l) => l.size === size);
  console.log(
    `${size}x${size}: ${group[0].minimum}-${group.at(-1).minimum} minimum moves`,
  );
}
