for (const [language, target] of [
  ["zh-TW", "twp"],
  ["zh-HK", "hk"],
]) {
  const convert = OpenCC.Converter({ from: "cn", to: target });
  const localize = (text) =>
    regionalTerms[language].reduce(
      (value, [from, to]) => value.replaceAll(from, to),
      text === "冲" || text === "冲煞"
        ? convert(text).replace("衝", "沖")
        : convert(text),
    );
  write(
    language,
    'WorkTimeApp.data.locales["' + language + '"]',
    Object.fromEntries(
      Object.entries(data.locales["zh-CN"]).map(([key, value]) => [
        key,
        translateMarkup(value, localize),
      ]),
    ),
  );
  write(
    "content-" + language,
    'WorkTimeApp.data.contentLocales["' + language + '"]',
    Object.fromEntries(
      Object.keys(data.contentEnglish).map((key) => [key, localize(key)]),
    ),
  );
  // Generate a finite display dictionary from the bundled lunar library. User
  // text, archive identities and lookup keys never pass through conversion.
  const lunarContext = {};
  require("node:vm").runInNewContext(
    fs.readFileSync(path.join(root, "assets/vendor/lunar.js"), "utf8"),
    lunarContext,
  );
  const lunarStrings = new Set();
  function collect(value) {
    if (typeof value === "string" && /[\u3400-\u9fff]/.test(value))
      lunarStrings.add(value);
    else if (Array.isArray(value)) value.forEach(collect);
    else if (value && typeof value === "object")
      Object.values(value).forEach(collect);
  }
  collect(lunarContext.LunarUtil);
  collect(lunarContext.SolarUtil);
  // Capture individual characters too for composite lunar prose such as 閏四月.
  for (const text of [...lunarStrings])
    for (const char of text)
      if (/[\u3400-\u9fff]/.test(char)) lunarStrings.add(char);
  const contentFile = path.join(
    root,
    "assets/js/locales/content-" + language + ".js",
  );
  fs.appendFileSync(
    contentFile,
    "Object.assign(WorkTimeApp.data.contentLocales[" +
      JSON.stringify(language) +
      "], " +
      JSON.stringify(
        Object.fromEntries(
          [...lunarStrings]
            .filter((key) => key.length < 100)
            .map((key) => [key, localize(key)]),
        ),
        null,
        2,
      ) +
      ");\n",
  );
  for (let month = 1; month <= 12; month++) {
    const name = String(month).padStart(2, "0") + ".js";
    const context = { WorkTimeApp: { data: { dateInfo: { history: {} } } } };
    require("node:vm").runInNewContext(
      fs.readFileSync(path.join(root, "assets/data/history", name), "utf8"),
      context,
    );
    const history = Object.fromEntries(
      Object.entries(context.WorkTimeApp.data.dateInfo.history).map(
        ([day, events]) => [
          day,
          events.map((event) => ({ ...event, text: convert(event.text) })),
        ],
      ),
    );
    const directory = path.join(root, "assets/data/history", language);
    fs.mkdirSync(directory, { recursive: true });
    fs.writeFileSync(
      path.join(directory, name),
      '"use strict";\n// Generated from Chinese history with OpenCC; upstream attribution is unchanged.\nWorkTimeApp.data.dateInfo.historyLocales ||= {};\nWorkTimeApp.data.dateInfo.historyLocales[' +
        JSON.stringify(language) +
        "] ||= {};\nObject.assign(WorkTimeApp.data.dateInfo.historyLocales[" +
        JSON.stringify(language) +
        "], " +
        JSON.stringify(history) +
        ");\n",
    );
  }
}
