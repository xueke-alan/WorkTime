"use strict";
/** Deterministic offline catalogs. Translation sources are indexed against source.json,
 * never against a moving catalog order; a missing new phrase fails generation. */
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const OpenCC = require("opencc-js");
const {
  root,
  readCatalogs,
  translateMarkup,
} = require("./lib/locale-source.cjs");
const data = readCatalogs();
const source = JSON.parse(
  fs.readFileSync(path.join(__dirname, "i18n/source.json"), "utf8"),
);
const languages = ["ko", "ja", "es", "de", "fr"];
const translations = new Map();
for (const file of fs
  .readdirSync(path.join(__dirname, "i18n"))
  .filter((name) => name.endsWith(".txt")))
  for (const line of fs
    .readFileSync(path.join(__dirname, "i18n", file), "utf8")
    .trim()
    .split(/\r?\n/)) {
    const [id, ...values] = line.split("|");
    assert.equal(values.length, languages.length, file + ": " + id);
    assert.ok(source[Number(id)], "Unknown source index " + id);
    assert.ok(!translations.has(source[Number(id)]), "Duplicate source " + id);
    translations.set(source[Number(id)], values);
  }
function write(name, property, object) {
  fs.writeFileSync(
    path.join(root, "assets/js/locales/" + name + ".js"),
    '"use strict";\n// Generated by scripts/generate-locales.cjs; edit scripts/i18n sources.\nWorkTimeApp.data.locales ||= {};\nWorkTimeApp.data.contentLocales ||= {};\n' +
      property +
      " = " +
      JSON.stringify(object, null, 2) +
      ";\n",
  );
}
const reserved = /^(?:worktime-|https?:|CC BY-SA|°C|h$|HH:MM|12:00|13:00)/;
for (const [index, language] of languages.entries()) {
  function translate(text) {
    const key = text.trim();
    if (!/[A-Za-z]/.test(key) || reserved.test(key)) return text;
    assert.ok(translations.has(key), "Missing phrase: " + key);
    return text.replace(key, () => translations.get(key)[index]);
  }
  write(
    language,
    'WorkTimeApp.data.locales["' + language + '"]',
    Object.fromEntries(
      Object.entries(data.locales.en).map(([key, value]) => [
        key,
        translateMarkup(value, translate),
      ]),
    ),
  );
  write(
    "content-" + language,
    'WorkTimeApp.data.contentLocales["' + language + '"]',
    Object.fromEntries(
      Object.entries(data.contentEnglish).map(([key, value]) => [
        key,
        translate(value),
      ]),
    ),
  );
}
